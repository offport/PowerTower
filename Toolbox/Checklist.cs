    /// <summary>One checklist result. Status: "pass" · "fail" · "warn" · "na" · "info".</summary>
    public class CheckItem
    {
        public string Id = "", Category = "", Name = "", Question = "", Status = "info", Detail = "", Evidence = "";   // Id: the stable check id (PT-W-…), assigned by Frameworks for reports and mappings
        public CheckItem() { }
        public CheckItem(string cat, string name, string question, string status, string detail, string evidence) { Category = cat; Name = name; Question = question ?? ""; Status = status; Detail = detail ?? ""; Evidence = evidence ?? ""; }
        public string StatusText { get { return Status == "pass" ? "PASS" : Status == "fail" ? "FAIL" : Status == "warn" ? "REVIEW" : Status == "na" ? "N/A" : "info"; } }
    }

    public class CheckReport
    {
        public string Host = Environment.MachineName, User = Environment.UserDomainName + "\\" + Environment.UserName, Os = "", When = DateTime.Now.ToString("yyyy-MM-dd HH:mm:ss");
        public bool Elevated; public readonly List<CheckItem> Items = new List<CheckItem>();
        public int Count(string s) { int n = 0; foreach (CheckItem i in Items) if (i.Status == s) n++; return n; }
        public int Pass { get { return Count("pass"); } } public int Fail { get { return Count("fail"); } } public int Warn { get { return Count("warn"); } }
        public int Scored { get { return Pass + Fail + Warn; } }
        public int Score { get { int s = Scored; return s == 0 ? 0 : (int)Math.Round(100.0 * (Pass + 0.5 * Warn) / s); } }
        public List<string> Categories() { List<string> l = new List<string>(); foreach (CheckItem i in Items) if (!l.Contains(i.Category)) l.Add(i.Category); return l; }
        public string FileStem { get { return "checklist_" + Host + "_" + DateTime.Now.ToString("yyyyMMdd-HHmmss"); } }

        public string ToMarkdown()
        {
            StringBuilder sb = new StringBuilder();
            sb.Append("# Security Checklist — ").Append(Host).Append("\n\n");
            sb.Append("- **Host:** ").Append(Host).Append("\n- **User:** ").Append(User).Append("\n- **OS:** ").Append(Os).Append("\n- **Collected:** ").Append(When).Append("\n- **Elevated:** ").Append(Elevated ? "yes" : "no").Append("\n");
            sb.Append("- **Result:** ").Append(Pass).Append(" pass · ").Append(Fail).Append(" fail · ").Append(Warn).Append(" review · score ").Append(Score).Append("/100\n\n");
            foreach (string cat in Categories())
            {
                sb.Append("## ").Append(cat).Append("\n\n| Check | Result | Detail | Evidence |\n|---|---|---|---|\n");
                foreach (CheckItem i in Items) if (i.Category == cat) sb.Append("| ").Append(Md(i.Name)).Append(" | ").Append(i.StatusText).Append(" | ").Append(Md(i.Detail)).Append(" | ").Append(Md(i.Evidence)).Append(" |\n");
                sb.Append("\n");
            }
            sb.Append("\n_Generated by PowerTower · Security Checklist. For authorized use only._\n");
            return sb.ToString();
        }
        static string Md(string s) { if (s == null) return ""; return s.Replace("\\", "\\\\").Replace("|", "\\|").Replace("\r", " ").Replace("\n", "<br>"); }

        public string ToJson()
        {
            StringBuilder sb = new StringBuilder();
            sb.Append("{\n  \"report\": \"Security Checklist\",\n  \"host\": ").Append(Json.Quote(Host)).Append(",\n  \"os\": ").Append(Json.Quote(Os)).Append(",\n  \"collected\": ").Append(Json.Quote(When)).Append(",\n  \"elevated\": ").Append(Elevated ? "true" : "false").Append(",\n");
            sb.Append("  \"summary\": { \"pass\": ").Append(Pass).Append(", \"fail\": ").Append(Fail).Append(", \"review\": ").Append(Warn).Append(", \"score\": ").Append(Score).Append(" },\n  \"checks\": [\n");
            for (int i = 0; i < Items.Count; i++) { CheckItem it = Items[i]; sb.Append("    { \"category\": ").Append(Json.Quote(it.Category)).Append(", \"check\": ").Append(Json.Quote(it.Name)).Append(", \"question\": ").Append(Json.Quote(it.Question)).Append(", \"status\": ").Append(Json.Quote(it.Status)).Append(", \"detail\": ").Append(Json.Quote(it.Detail)).Append(", \"evidence\": ").Append(Json.Quote(it.Evidence)).Append(" }").Append(i < Items.Count - 1 ? "," : "").Append("\n"); }
            sb.Append("  ]\n}\n");
            return sb.ToString();
        }
        public List<PdfLine> ToLines()
        {
            List<PdfLine> l = new List<PdfLine>();
            l.Add(new PdfLine("Security Checklist", true, 15, 0));
            l.Add(new PdfLine(Host + "    " + When + "    Elevated: " + (Elevated ? "yes" : "no"), false, 9, 0));
            l.Add(new PdfLine("OS: " + Os, false, 9, 0));
            l.Add(new PdfLine("Score " + Score + "/100  ·  " + Pass + " pass, " + Fail + " fail, " + Warn + " to review", true, 10, 0));
            l.Add(new PdfLine("", false, 9, 0));
            foreach (string cat in Categories())
            {
                l.Add(new PdfLine("", false, 6, 0)); l.Add(new PdfLine(cat.ToUpperInvariant(), true, 12, 0));
                foreach (CheckItem i in Items) if (i.Category == cat)
                    {
                        string mark = i.Status == "fail" ? "[FAIL] " : i.Status == "warn" ? "[REVIEW] " : i.Status == "pass" ? "[PASS] " : i.Status == "na" ? "[N/A] " : "[info] ";
                        l.Add(new PdfLine("  " + mark + i.Name + " — " + i.Detail, false, 9, 0));
                        if (i.Evidence.Length > 0) l.Add(new PdfLine("        " + i.Evidence, false, 8, 0));
                    }
            }
            l.Add(new PdfLine("", false, 9, 0)); l.Add(new PdfLine("Generated by PowerTower - Security Checklist. For authorized use only.", false, 8, 0));
            return l;
        }
        public void SavePdf(string path) { Pdf.Write(path, ToLines()); }
    }

    public class ChecklistScan
    {
        public readonly CheckReport Report = new CheckReport();
        public readonly List<string> Log = new List<string>(), Errors = new List<string>();
        public event Action<string> Progress; public event Action Phase; public event Action Finished; public event Action<string, string, string> Step; public volatile bool Cancel; public bool Running; public DateTime StartedAt, FinishedAt;
        public static readonly string[] StepLabels = { "Accounts", "Disk", "Antivirus", "Remote access", "VPN", "USB", "Firewall" };
        readonly object sync = new object();
        void Say(string s) { lock (sync) Log.Add(DateTime.Now.ToString("HH:mm:ss") + "  " + s); if (Progress != null) Progress(s); }
        void StepTo(string label, string state) { if (Step != null) Step(label, state, null); }
        void Add(string cat, string name, string question, string status, string detail, string evidence) { lock (sync) Report.Items.Add(new CheckItem(cat, name, question, status, detail, evidence)); Done(); }
        void Fail(string cat, string what, Exception ex) { lock (sync) Errors.Add(cat + " / " + what + ": " + ex.Message); Add(cat, what, "", "na", "could not be checked", Trim(ex.Message)); }
        static string Trim(string s) { s = (s ?? "").Replace("\r", " ").Replace("\n", " ").Trim(); return s.Length > 160 ? s.Substring(0, 160) + "…" : s; }
        void Done() { if (Phase != null) Phase(); }
        public void RunInBackground() { Thread t = new Thread(Run); t.IsBackground = true; t.Name = "checklist"; t.Start(); }

        public void Run()
        {
            Running = true; StartedAt = DateTime.Now; lock (sync) { Report.Items.Clear(); Errors.Clear(); }
            Report.Elevated = IsAdmin(); try { Report.Os = Inventory.Os().Summary; } catch { }
            try
            {
                StepTo("Accounts", "running"); Say("accounts and credentials…"); Accounts(); StepTo("Accounts", "done"); if (Cancel) return;
                StepTo("Disk", "running"); Say("disk encryption…"); Disk(); StepTo("Disk", "done"); if (Cancel) return;
                StepTo("Antivirus", "running"); Say("antivirus and security products…"); Antivirus(); StepTo("Antivirus", "done"); if (Cancel) return;
                StepTo("Remote access", "running"); Say("remote-access tools…"); RemoteAccess(); StepTo("Remote access", "done"); if (Cancel) return;
                StepTo("VPN", "running"); Say("VPN tools…"); Vpn(); StepTo("VPN", "done"); if (Cancel) return;
                StepTo("USB", "running"); Say("USB and removable storage…"); Usb(); StepTo("USB", "done"); if (Cancel) return;
                StepTo("Firewall", "running"); Say("firewall and updates…"); Firewall(); StepTo("Firewall", "done");
                Say("done · " + Report.Pass + " pass, " + Report.Fail + " fail, " + Report.Warn + " review · score " + Report.Score + "/100");
            }
            catch (Exception ex) { lock (sync) Errors.Add("checklist: " + ex.Message); Say("✗ " + ex.Message); }
            finally { Running = false; FinishedAt = DateTime.Now; if (Finished != null) Finished(); }
        }
        static bool IsAdmin() { try { return new System.Security.Principal.WindowsPrincipal(System.Security.Principal.WindowsIdentity.GetCurrent()).IsInRole(System.Security.Principal.WindowsBuiltInRole.Administrator); } catch { return false; } }
        static bool ToBool(object o) { try { return o != null && Convert.ToBoolean(o); } catch { return false; } }
        static string RegStr(RegistryHive hive, string path, string name) { try { using (RegistryKey b = RegistryKey.OpenBaseKey(hive, RegistryView.Registry64)) using (RegistryKey k = b.OpenSubKey(path)) { object v = k == null ? null : k.GetValue(name); return v == null ? null : Convert.ToString(v); } } catch { return null; } }
        static int RegInt(RegistryHive hive, string path, string name, int def) { try { using (RegistryKey b = RegistryKey.OpenBaseKey(hive, RegistryView.Registry64)) using (RegistryKey k = b.OpenSubKey(path)) { object v = k == null ? null : k.GetValue(name); return v == null ? def : Convert.ToInt32(v); } } catch { return def; } }

        // ── 1 · accounts ──
        void Accounts()
        {
            const string C = "Accounts & Credentials";
            HashSet<string> admins = new HashSet<string>(StringComparer.OrdinalIgnoreCase);
            try { string host = Environment.MachineName.Replace("'", "''"); using (ManagementObjectSearcher q = new ManagementObjectSearcher(new ManagementScope(@"\\.\root\cimv2"), new ObjectQuery("ASSOCIATORS OF {Win32_Group.Domain='" + host + "',Name='Administrators'} WHERE ResultClass=Win32_Account"))) foreach (ManagementObject o in q.Get()) admins.Add(Convert.ToString(o["Name"])); } catch { }
            try
            {
                List<string> noPw = new List<string>(); List<string> adminNoPw = new List<string>(); bool adminEnabled = false, guestEnabled = false;
                using (ManagementObjectSearcher q = new ManagementObjectSearcher("SELECT Name, Disabled, PasswordRequired, SID FROM Win32_UserAccount WHERE LocalAccount=True"))
                    foreach (ManagementObject o in q.Get())
                    {
                        string name = Convert.ToString(o["Name"]); bool disabled = ToBool(o["Disabled"]); bool pwReq = ToBool(o["PasswordRequired"]); string sid = Convert.ToString(o["SID"]) ?? "";
                        if (sid.EndsWith("-500") && !disabled) adminEnabled = true;
                        if (sid.EndsWith("-501") && !disabled) guestEnabled = true;
                        if (!disabled && !pwReq) { noPw.Add(name); if (admins.Contains(name)) adminNoPw.Add(name); }
                    }
                Add(C, "Administrator without a password", "Is there an admin account with no password required?", adminNoPw.Count == 0 ? "pass" : "fail", adminNoPw.Count == 0 ? "no enabled admin account allows a blank password" : adminNoPw.Count + " admin account(s) require no password", string.Join(", ", adminNoPw.ToArray()));
                Add(C, "Accounts with no password required", "Do any enabled accounts allow a blank password?", noPw.Count == 0 ? "pass" : "warn", noPw.Count == 0 ? "every enabled local account requires a password" : noPw.Count + " account(s) do not require a password", string.Join(", ", noPw.ToArray()));
                Add(C, "Built-in Administrator account", "Is the built-in Administrator account disabled?", adminEnabled ? "warn" : "pass", adminEnabled ? "the built-in Administrator (RID 500) is enabled" : "disabled", "");
                Add(C, "Guest account", "Is the Guest account disabled?", guestEnabled ? "fail" : "pass", guestEnabled ? "the Guest account is enabled" : "disabled", "");
            }
            catch (Exception ex) { Fail(C, "local accounts", ex); }
            // stored auto-logon password = a default/plaintext credential on disk
            try
            {
                string autolog = RegStr(RegistryHive.LocalMachine, @"SOFTWARE\Microsoft\Windows NT\CurrentVersion\Winlogon", "AutoAdminLogon");
                string defPw = RegStr(RegistryHive.LocalMachine, @"SOFTWARE\Microsoft\Windows NT\CurrentVersion\Winlogon", "DefaultPassword");
                bool auto = autolog == "1"; bool hasPw = !string.IsNullOrEmpty(defPw);
                Add(C, "Stored auto-logon password", "Is a plaintext logon password stored in the registry?", (auto && hasPw) || hasPw ? "fail" : "pass", hasPw ? "a DefaultPassword is stored in Winlogon" + (auto ? " and auto-logon is on" : "") : (auto ? "auto-logon is on but no stored password found" : "no stored logon password"), hasPw ? "HKLM\\...\\Winlogon\\DefaultPassword" : "");
            }
            catch (Exception ex) { Fail(C, "auto-logon", ex); }
            Add(C, "Default / manufacturer credentials", "Have default administrator and vendor credentials been changed on every endpoint?", "info", "cannot be verified from software alone — this checks the local indicators above (blank passwords, enabled default accounts, stored credentials); confirming a device was changed from a vendor default needs a login attempt per device", "");
        }

        // ── 2 · disk ──
        void Disk()
        {
            const string C = "Disk Encryption";
            try
            {
                int on = 0, off = 0; List<string> offList = new List<string>(); bool any = false;
                using (ManagementObjectSearcher q = new ManagementObjectSearcher(new ManagementScope(@"\\.\root\cimv2\Security\MicrosoftVolumeEncryption"), new ObjectQuery("SELECT DriveLetter, ProtectionStatus FROM Win32_EncryptableVolume")))
                    foreach (ManagementObject o in q.Get()) { any = true; int ps = 0; try { ps = Convert.ToInt32(o["ProtectionStatus"]); } catch { } string dl = Convert.ToString(o["DriveLetter"]); if (ps == 1) on++; else { off++; offList.Add(dl); } }
                if (!any) Add(C, "Disk encryption (BitLocker)", "Is the disk encrypted?", "na", "no encryptable volumes reported — reading BitLocker needs administrator rights", "");
                else Add(C, "Disk encryption (BitLocker)", "Is the disk encrypted?", off == 0 ? "pass" : "warn", off == 0 ? on + " volume(s) protected" : off + " of " + (on + off) + " volume(s) not encrypted", off == 0 ? "" : "unprotected: " + string.Join(", ", offList.ToArray()));
            }
            catch (Exception ex) { Add(C, "Disk encryption (BitLocker)", "Is the disk encrypted?", "na", "could not read BitLocker (needs administrator rights)", Trim(ex.Message)); }
        }

        // ── 3 · antivirus & security products ──
        static void DecodeState(int state, out bool enabled, out bool upToDate) { int scanner = (state >> 8) & 0xFF; int def = state & 0xFF; enabled = (scanner & 0x10) != 0 || (scanner & 0x01) != 0; upToDate = (def & 0x10) == 0; }
        void Antivirus()
        {
            const string C = "Antivirus & Security Products";
            int avCount = 0, avEnabled = 0;
            foreach (string cls in new string[] { "AntiVirusProduct", "AntiSpywareProduct", "FirewallProduct" })
            {
                try
                {
                    using (ManagementObjectSearcher q = new ManagementObjectSearcher(new ManagementScope(@"\\.\root\SecurityCenter2"), new ObjectQuery("SELECT displayName, productState FROM " + cls)))
                        foreach (ManagementObject o in q.Get())
                        {
                            string name = Convert.ToString(o["displayName"]); int state = 0; try { state = Convert.ToInt32(o["productState"]); } catch { }
                            bool enabled, upToDate; DecodeState(state, out enabled, out upToDate);
                            string kind = cls == "AntiVirusProduct" ? "antivirus" : cls == "AntiSpywareProduct" ? "antispyware" : "firewall";
                            if (cls == "AntiVirusProduct") { avCount++; if (enabled) avEnabled++; }
                            Add(C, "Registered " + kind + ": " + name, "Which security products are installed and enabled?", enabled ? "info" : "warn", (enabled ? "enabled" : "DISABLED") + " · " + (upToDate ? "up to date" : "out of date"), "Security Center state 0x" + state.ToString("x"));
                        }
                }
                catch (Exception ex) { if (cls == "AntiVirusProduct") Fail(C, "Security Center", ex); }
            }
            // Defender's own status (real-time, running mode)
            try
            {
                using (ManagementObjectSearcher q = new ManagementObjectSearcher(new ManagementScope(@"\\.\root\Microsoft\Windows\Defender"), new ObjectQuery("SELECT RealTimeProtectionEnabled, AntivirusEnabled, AMRunningMode, AntivirusSignatureLastUpdated FROM MSFT_MpComputerStatus")))
                    foreach (ManagementObject o in q.Get())
                    {
                        bool rtp = ToBool(o["RealTimeProtectionEnabled"]); string modeStr = Convert.ToString(o["AMRunningMode"]);
                        Add(C, "Microsoft Defender real-time protection", "Is real-time antivirus protection on?", rtp ? "pass" : (avEnabled > 0 ? "warn" : "fail"), rtp ? "enabled" : "disabled", modeStr != null && modeStr.Length > 0 ? "running mode: " + modeStr : "");
                        if (modeStr != null && modeStr.IndexOf("Passive", StringComparison.OrdinalIgnoreCase) >= 0) Add(C, "Defender running mode", "Is Defender active or passive?", "info", "passive (another antivirus is primary)", modeStr);
                    }
            }
            catch (Exception ex) { Fail(C, "Defender status", ex); }
            Add(C, "Antivirus available and enabled", "Is antivirus present and turned on?", avEnabled > 0 ? "pass" : "fail", avEnabled > 0 ? avEnabled + " of " + avCount + " registered antivirus product(s) enabled" : (avCount > 0 ? "an antivirus is registered but reports disabled" : "no antivirus registered with Security Center"), "");
            // known EDR / monitoring agents by service or process name
            try
            {
                Signals sig = Signals.Collect();
                List<string> found = sig.Match(EdrKeywords);
                Add(C, "Endpoint detection & response (EDR)", "Is an EDR or monitoring agent present?", found.Count > 0 ? "info" : "info", found.Count > 0 ? string.Join(", ", found.ToArray()) : "no well-known EDR/monitoring agent detected", found.Count > 0 ? "matched by service or process name" : "checked CrowdStrike, SentinelOne, Carbon Black, Cortex, Defender for Endpoint, Sophos, ESET, Sysmon and others");
            }
            catch (Exception ex) { Fail(C, "EDR agents", ex); }
        }

