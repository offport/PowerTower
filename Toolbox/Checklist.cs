    /// <summary>The service, process and installed-software names on the machine, for keyword matching.</summary>
    public class Signals
    {
        public readonly List<string> Services = new List<string>(), Processes = new List<string>(), Software = new List<string>();
        public static Signals Collect()
        {
            Signals s = new Signals();
            try { using (ManagementObjectSearcher q = new ManagementObjectSearcher("SELECT Name, DisplayName, PathName, State FROM Win32_Service")) foreach (ManagementObject o in q.Get()) s.Services.Add((Convert.ToString(o["Name"]) + " " + Convert.ToString(o["DisplayName"]) + " " + Convert.ToString(o["PathName"]) + " " + Convert.ToString(o["State"]))); } catch { }
            try { using (ManagementObjectSearcher q = new ManagementObjectSearcher("SELECT Name FROM Win32_Process")) foreach (ManagementObject o in q.Get()) s.Processes.Add(Convert.ToString(o["Name"])); } catch { }
            try { foreach (Software sw in Inventory.Installed()) s.Software.Add(sw.Name + " " + sw.Publisher); } catch { }
            return s;
        }
        /// <summary>Returns the labels whose keyword appears in any service, process or installed name.</summary>
        public List<string> Match(string[][] table)
        {
            List<string> found = new List<string>();
            foreach (string[] entry in table)
            {
                string label = entry[0], kw = entry[1]; if (Hit(Services, kw) || Hit(Processes, kw) || Hit(Software, kw)) { if (!found.Contains(label)) found.Add(label); }
            }
            return found;
        }
        static bool Hit(List<string> hay, string kw) { foreach (string s in hay) if (s != null && s.IndexOf(kw, StringComparison.OrdinalIgnoreCase) >= 0) return true; return false; }
    }


