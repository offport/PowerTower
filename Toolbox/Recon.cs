        void EventGroup(string S, string group, string log, int id, int max, string risk)
        {
            try
            {
                EventLogQuery query = new EventLogQuery(log, PathType.LogName, "*[System[(EventID=" + id + ")]]"); query.ReverseDirection = true;
                using (EventLogReader r = new EventLogReader(query))
                {
                    int n = 0; EventRecord e;
                    while (n < max && (e = r.ReadEvent()) != null)
                    {
                        n++; string when = e.TimeCreated.HasValue ? e.TimeCreated.Value.ToString("yyyy-MM-dd HH:mm:ss") : "?"; string msg = ""; try { msg = e.FormatDescription(); } catch { }
                        msg = (msg ?? "").Replace("\r", " ").Replace("\n", " · "); if (msg.Length > 200) msg = msg.Substring(0, 200) + "…";
                        Add(S, group, when, msg.Length > 0 ? msg : "(no description)", "", risk);
                    }
                    if (n == 0) Add(S, group, "events", "none in the log", "", "good");
                }
            }
            catch (UnauthorizedAccessException) { Add(S, group, "events", "needs administrator rights", "the " + log + " log is not readable without elevation", "info"); }
            catch (EventLogException ex) { Add(S, group, "events", "unavailable", Trim(ex.Message), "info"); }
            catch (Exception ex) { FailItem(S, group, log + " events", ex); }
        }

