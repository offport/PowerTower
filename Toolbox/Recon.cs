    /// <summary>One collected fact. Risk: "" · "good" · "info" · "warn" · "bad".</summary>
    public class ReconItem
    {
        public string Section = "", Group = "", Name = "", Value = "", Note = "", Risk = "";
        public ReconItem() { }
        public ReconItem(string section, string group, string name, string value, string note, string risk) { Section = section; Group = group; Name = name; Value = value ?? ""; Note = note ?? ""; Risk = risk ?? ""; }
        public string RiskText { get { return Risk == "bad" ? "risk" : Risk == "warn" ? "review" : Risk == "good" ? "ok" : Risk == "info" ? "info" : ""; } }
    }

    /// <summary>The whole report: metadata plus the flat list of facts, with Markdown / JSON / PDF renderers.</summary>
    public class ReconReport
    {
        public string Host = Environment.MachineName, User = Environment.UserDomainName + "\\" + Environment.UserName, Os = "", When = DateTime.Now.ToString("yyyy-MM-dd HH:mm:ss");
        public bool Elevated; public readonly List<ReconItem> Items = new List<ReconItem>();
        public int Warn { get { int n = 0; foreach (ReconItem i in Items) if (i.Risk == "warn") n++; return n; } }
        public int Bad { get { int n = 0; foreach (ReconItem i in Items) if (i.Risk == "bad") n++; return n; } }
        public List<string> Sections()
        {
            List<string> s = new List<string>(); foreach (ReconItem i in Items) if (!s.Contains(i.Section)) s.Add(i.Section); return s;
        }

        public string FileStem { get { return "recon_" + Host + "_" + DateTime.Now.ToString("yyyyMMdd-HHmmss"); } }

        // ── Markdown ──
        public string ToMarkdown()
        {
            StringBuilder sb = new StringBuilder();
            sb.Append("# System Recon & Audit — ").Append(Host).Append("\n\n");
            sb.Append("- **Host:** ").Append(Host).Append("\n");
            sb.Append("- **User:** ").Append(User).Append("\n");
            sb.Append("- **OS:** ").Append(Os).Append("\n");
            sb.Append("- **Collected:** ").Append(When).Append("\n");
            sb.Append("- **Elevated:** ").Append(Elevated ? "yes" : "no").Append("\n");
            sb.Append("- **Summary:** ").Append(Items.Count).Append(" facts · ").Append(Bad).Append(" risk · ").Append(Warn).Append(" to review\n\n");
            foreach (string sec in Sections())
            {
                sb.Append("## ").Append(sec).Append("\n\n"); string group = null;
                List<ReconItem> inSec = Items.FindAll(delegate (ReconItem i) { return i.Section == sec; });
                foreach (ReconItem i in inSec)
                {
                    if (i.Group != group) { group = i.Group; if (group.Length > 0) sb.Append("### ").Append(group).Append("\n\n"); sb.Append("| Item | Value | Note |\n|---|---|---|\n"); }
                    sb.Append("| ").Append(Marker(i.Risk)).Append(Md(i.Name)).Append(" | ").Append(Md(i.Value)).Append(" | ").Append(Md(i.Note)).Append(" |\n");
                }
                sb.Append("\n");
            }
            sb.Append("\n_Generated by PowerTower · System Recon & Audit. For authorized use only._\n");
            return sb.ToString();
        }
        static string Marker(string risk) { return risk == "bad" ? "❗ " : risk == "warn" ? "⚠ " : risk == "good" ? "✔ " : ""; }
        static string Md(string s) { if (s == null) return ""; return s.Replace("\\", "\\\\").Replace("|", "\\|").Replace("\r", " ").Replace("\n", "<br>"); }

        // ── JSON ──
        public string ToJson()
        {
            StringBuilder sb = new StringBuilder();
            sb.Append("{\n  \"report\": \"System Recon & Audit\",\n");
            sb.Append("  \"host\": ").Append(Json.Quote(Host)).Append(",\n  \"user\": ").Append(Json.Quote(User)).Append(",\n  \"os\": ").Append(Json.Quote(Os)).Append(",\n  \"collected\": ").Append(Json.Quote(When)).Append(",\n  \"elevated\": ").Append(Elevated ? "true" : "false").Append(",\n");
            sb.Append("  \"summary\": { \"facts\": ").Append(Items.Count).Append(", \"risks\": ").Append(Bad).Append(", \"review\": ").Append(Warn).Append(", \"sections\": ").Append(Sections().Count).Append(" },\n");
            sb.Append("  \"sections\": [\n");
            List<string> secs = Sections();
            for (int s = 0; s < secs.Count; s++)
            {
                sb.Append("    { \"name\": ").Append(Json.Quote(secs[s])).Append(", \"items\": [\n");
                List<ReconItem> inSec = Items.FindAll(delegate (ReconItem i) { return i.Section == secs[s]; });
                for (int i = 0; i < inSec.Count; i++)
                {
                    ReconItem it = inSec[i];
                    sb.Append("      { \"group\": ").Append(Json.Quote(it.Group)).Append(", \"name\": ").Append(Json.Quote(it.Name)).Append(", \"value\": ").Append(Json.Quote(it.Value)).Append(", \"note\": ").Append(Json.Quote(it.Note)).Append(", \"risk\": ").Append(Json.Quote(it.Risk)).Append(" }").Append(i < inSec.Count - 1 ? "," : "").Append("\n");
                }
                sb.Append("    ] }").Append(s < secs.Count - 1 ? "," : "").Append("\n");
            }
            sb.Append("  ]\n}\n");
            return sb.ToString();
        }

        // ── plain text lines (shared by the PDF writer) ──
        public List<PdfLine> ToLines()
        {
            List<PdfLine> l = new List<PdfLine>();
            l.Add(new PdfLine("System Recon & Audit", true, 15, 0));
            l.Add(new PdfLine(Host + "    " + When, false, 9, 0));
            l.Add(new PdfLine("User: " + User + "     Elevated: " + (Elevated ? "yes" : "no"), false, 9, 0));
            l.Add(new PdfLine("OS: " + Os, false, 9, 0));
            l.Add(new PdfLine(Items.Count + " facts collected · " + Bad + " flagged as risk · " + Warn + " to review", false, 9, 0));
            l.Add(new PdfLine("", false, 9, 0));
            foreach (string sec in Sections())
            {
                l.Add(new PdfLine("", false, 6, 0)); l.Add(new PdfLine(sec.ToUpperInvariant(), true, 12, 0));
                string group = null; List<ReconItem> inSec = Items.FindAll(delegate (ReconItem i) { return i.Section == sec; });
                foreach (ReconItem i in inSec)
                {
                    if (i.Group != group) { group = i.Group; if (group.Length > 0) l.Add(new PdfLine("  " + group, true, 9, 0)); }
                    string mark = i.Risk == "bad" ? "[!] " : i.Risk == "warn" ? "[~] " : "";
                    string name = i.Name.Length > 0 ? (i.Name + ": ") : "";
                    string line = "    " + mark + name + i.Value + (i.Note.Length > 0 ? "   (" + i.Note + ")" : "");
                    l.Add(new PdfLine(line, false, 9, 0));
                }
            }
            l.Add(new PdfLine("", false, 9, 0));
            l.Add(new PdfLine("Generated by PowerTower - System Recon & Audit. For authorized use only.", false, 8, 0));
            return l;
        }
        public void SavePdf(string path) { Pdf.Write(path, ToLines()); }
    }

    // ───────────────────────────── a minimal text PDF writer ─────────────────────────────
    public class PdfLine { public string Text; public bool Bold; public float Size; public int Indent; public PdfLine(string text, bool bold, float size, int indent) { Text = text; Bold = bold; Size = size; Indent = indent; } }
    /// <summary>Writes a paginated, monospaced (Courier) PDF from a list of lines. Base-14 fonts only, so no font embedding; text is reduced to WinAnsi/ASCII.</summary>
    public static class Pdf
    {
        const float PW = 612, PH = 792, ML = 48, MR = 48, MT = 54, MB = 48, LineH = 12.5f;
        public static void Write(string path, List<PdfLine> lines)
        {
            List<PdfLine> flat = new List<PdfLine>();
            foreach (PdfLine ln in lines)
            {
                string t = Ascii(ln.Text); float w = ln.Size * 0.6f; int max = Math.Max(10, (int)((PW - ML - MR - ln.Indent) / w));
                if (t.Length <= max) { flat.Add(new PdfLine(t, ln.Bold, ln.Size, ln.Indent)); continue; }
                foreach (string piece in Wrap(t, max)) flat.Add(new PdfLine(piece, ln.Bold, ln.Size, ln.Indent));
            }
            int perPage = Math.Max(1, (int)((PH - MT - MB) / LineH));
            List<List<PdfLine>> pages = new List<List<PdfLine>>(); for (int i = 0; i < flat.Count; i += perPage) pages.Add(flat.GetRange(i, Math.Min(perPage, flat.Count - i)));
            if (pages.Count == 0) pages.Add(new List<PdfLine>());

            List<byte[]> objs = new List<byte[]>();
            int nPages = pages.Count; int firstPage = 5; // 1 catalog, 2 pages, 3 font, 4 font-bold, then page/content pairs
            List<int> pageIds = new List<int>(); for (int i = 0; i < nPages; i++) pageIds.Add(firstPage + i * 2 + 1);
            StringBuilder kids = new StringBuilder(); foreach (int id in pageIds) kids.Append(id).Append(" 0 R ");
            objs.Add(Bytes("<< /Type /Catalog /Pages 2 0 R >>"));
            objs.Add(Bytes("<< /Type /Pages /Kids [ " + kids.ToString().Trim() + " ] /Count " + nPages + " >>"));
            objs.Add(Bytes("<< /Type /Font /Subtype /Type1 /BaseFont /Courier /Encoding /WinAnsiEncoding >>"));
            objs.Add(Bytes("<< /Type /Font /Subtype /Type1 /BaseFont /Courier-Bold /Encoding /WinAnsiEncoding >>"));
            for (int p = 0; p < nPages; p++)
            {
                int contentId = firstPage + p * 2, pageId = firstPage + p * 2 + 1;
                StringBuilder cs = new StringBuilder(); float y = PH - MT;
                foreach (PdfLine ln in pages[p])
                {
                    if (ln.Text.Length > 0) cs.Append("BT /").Append(ln.Bold ? "F2" : "F1").Append(' ').Append(ln.Size.ToString(CultureInfo.InvariantCulture)).Append(" Tf ").Append((ML + ln.Indent).ToString(CultureInfo.InvariantCulture)).Append(' ').Append(y.ToString("0.##", CultureInfo.InvariantCulture)).Append(" Td (").Append(EscapePdf(ln.Text)).Append(") Tj ET\n");
                    y -= LineH;
                }
                byte[] stream = Encoding.ASCII.GetBytes(cs.ToString());
                byte[] head = Encoding.ASCII.GetBytes("<< /Length " + stream.Length + " >>\nstream\n");
                byte[] tail = Encoding.ASCII.GetBytes("\nendstream");
                byte[] content = new byte[head.Length + stream.Length + tail.Length]; Buffer.BlockCopy(head, 0, content, 0, head.Length); Buffer.BlockCopy(stream, 0, content, head.Length, stream.Length); Buffer.BlockCopy(tail, 0, content, head.Length + stream.Length, tail.Length);
                // ensure ids line up: content objects come before their page object
                while (objs.Count < contentId - 1) objs.Add(Bytes("<< >>"));
                objs.Add(content);
                objs.Add(Bytes("<< /Type /Page /Parent 2 0 R /MediaBox [0 0 612 792] /Resources << /Font << /F1 3 0 R /F2 4 0 R >> >> /Contents " + contentId + " 0 R >>"));
            }

            using (FileStream fs = new FileStream(path, FileMode.Create, FileAccess.Write))
            {
                List<long> offsets = new List<long>(); byte[] header = new byte[] { (byte)'%', (byte)'P', (byte)'D', (byte)'F', (byte)'-', (byte)'1', (byte)'.', (byte)'4', (byte)'\n', (byte)'%', 0xE2, 0xE3, 0xCF, 0xD3, (byte)'\n' }; fs.Write(header, 0, header.Length);
                for (int i = 0; i < objs.Count; i++)
                {
                    offsets.Add(fs.Position); byte[] pre = Encoding.ASCII.GetBytes((i + 1) + " 0 obj\n"); fs.Write(pre, 0, pre.Length); fs.Write(objs[i], 0, objs[i].Length); byte[] post = Encoding.ASCII.GetBytes("\nendobj\n"); fs.Write(post, 0, post.Length);
                }
                long xref = fs.Position; StringBuilder x = new StringBuilder(); x.Append("xref\n0 ").Append(objs.Count + 1).Append("\n0000000000 65535 f \n");
                foreach (long off in offsets) x.Append(off.ToString("0000000000")).Append(" 00000 n \n");
                x.Append("trailer\n<< /Size ").Append(objs.Count + 1).Append(" /Root 1 0 R >>\nstartxref\n").Append(xref).Append("\n%%EOF");
                byte[] xb = Encoding.ASCII.GetBytes(x.ToString()); fs.Write(xb, 0, xb.Length);
            }
        }
        static byte[] Bytes(string s) { return Encoding.ASCII.GetBytes(s); }
        static string EscapePdf(string s) { return s.Replace("\\", "\\\\").Replace("(", "\\(").Replace(")", "\\)"); }
        static List<string> Wrap(string s, int max)
        {
            List<string> o = new List<string>(); string[] words = s.Split(' '); StringBuilder cur = new StringBuilder();
            foreach (string w in words)
            {
                string word = w;
                while (word.Length > max) { if (cur.Length > 0) { o.Add(cur.ToString()); cur.Length = 0; } o.Add(word.Substring(0, max)); word = word.Substring(max); }
                if (cur.Length == 0) cur.Append(word);
                else if (cur.Length + 1 + word.Length <= max) cur.Append(' ').Append(word);
                else { o.Add(cur.ToString()); cur.Length = 0; cur.Append(word); }
            }
            if (cur.Length > 0) o.Add(cur.ToString()); if (o.Count == 0) o.Add(""); return o;
        }
        /// <summary>Reduce to characters Courier/WinAnsi can show; map the glyphs the app uses, drop the rest.</summary>
        static string Ascii(string s)
        {
            if (s == null) return ""; StringBuilder sb = new StringBuilder(s.Length);
            foreach (char c in s)
            {
                if (c >= 32 && c < 127) sb.Append(c);
                else switch (c) { case '✓': case '✔': sb.Append("OK"); break; case '✗': case '✖': case '❗': sb.Append('!'); break; case '⚠': sb.Append('~'); break; case '→': sb.Append("->"); break; case '·': case '•': sb.Append('-'); break; case '≥': sb.Append(">="); break; case '≤': sb.Append("<="); break; case '—': case '–': sb.Append('-'); break; case '“': case '”': sb.Append('"'); break; case '‘': case '’': sb.Append('\''); break; case '…': sb.Append("..."); break; case '\t': sb.Append("    "); break; default: if (c >= 160 && c <= 255) sb.Append(c); else sb.Append(' '); break; }
            }
            return sb.ToString();
        }
    }

    // ───────────────────────────── the audit ─────────────────────────────
    public class ReconScan
    {
        public bool DoEvents = true; public int ProcLimit = 600;
        public readonly ReconReport Report = new ReconReport();
        public readonly List<string> Log = new List<string>(), Errors = new List<string>();
        public event Action<string> Progress; public event Action Phase; public event Action Finished; public volatile bool Cancel; public bool Running; public DateTime StartedAt, FinishedAt;
        public event Action<string, string, string> Step; public static readonly string[] StepLabels = { "System", "Users", "Network", "Security", "Persistence", "Processes", "Events" };
        void StepTo(string label, string state) { if (Step != null) Step(label, state, null); }
        readonly object sync = new object();
        void Say(string s) { lock (sync) Log.Add(DateTime.Now.ToString("HH:mm:ss") + "  " + s); if (Progress != null) Progress(s); }
        void Add(string section, string group, string name, string value, string note, string risk) { lock (sync) Report.Items.Add(new ReconItem(section, group, name, Flat(value), Flat(note), risk)); }
        /// <summary>One line per fact: command lines and messages can span lines, a grid cell and a CSV row should not.</summary>
        static string Flat(string s) { if (string.IsNullOrEmpty(s)) return ""; if (s.IndexOf('\n') < 0 && s.IndexOf('\r') < 0 && s.IndexOf('\t') < 0) return s; s = s.Replace("\r\n", " ").Replace('\n', ' ').Replace('\r', ' ').Replace('\t', ' '); while (s.IndexOf("  ") >= 0) s = s.Replace("  ", " "); return s.Trim(); }
        void FailItem(string section, string group, string what, Exception ex) { string m = what + " could not be read: " + Trim(ex.Message); lock (sync) Errors.Add(section + " / " + what + ": " + ex.Message); Add(section, group, what, "unavailable", Trim(ex.Message), "info"); }
        static string Trim(string s) { s = (s ?? "").Replace("\r", " ").Replace("\n", " ").Trim(); return s.Length > 200 ? s.Substring(0, 200) + "…" : s; }
        void Done() { if (Phase != null) Phase(); }
        public void RunInBackground() { Thread t = new Thread(Run); t.IsBackground = true; t.Name = "recon"; t.Start(); }

        public void Run()
        {
            Running = true; StartedAt = DateTime.Now; lock (sync) { Report.Items.Clear(); Errors.Clear(); }
            Report.Elevated = IsAdmin();
            try
            {
                if (!DoEvents) StepTo("Events", "skipped");
                StepTo("System", "running"); Say("system information…"); System_(); Done(); StepTo("System", "done"); if (Cancel) return;
                StepTo("Users", "running"); Say("users and groups…"); Users_(); Done(); StepTo("Users", "done"); if (Cancel) return;
                StepTo("Network", "running"); Say("network…"); Network_(); Done(); StepTo("Network", "done"); if (Cancel) return;
                StepTo("Security", "running"); Say("security posture…"); Security_(); Done(); StepTo("Security", "done"); if (Cancel) return;
                StepTo("Persistence", "running"); Say("persistence surface…"); Persistence_(); Done(); StepTo("Persistence", "done"); if (Cancel) return;
                StepTo("Processes", "running"); Say("running processes…"); Processes_(); Done(); StepTo("Processes", "done"); if (Cancel) return;
                if (DoEvents) { StepTo("Events", "running"); Say("recent security events…"); Events_(); Done(); StepTo("Events", "done"); }
                Say("done · " + Report.Items.Count + " facts, " + Report.Bad + " risk, " + Report.Warn + " to review, in " + Fmt.Secs((DateTime.Now - StartedAt).TotalSeconds));
            }
            catch (Exception ex) { lock (sync) Errors.Add("audit: " + ex.Message); Say("✗ audit: " + ex.Message); }
            finally { Running = false; FinishedAt = DateTime.Now; if (Finished != null) Finished(); }
        }

        static bool IsAdmin() { try { return new System.Security.Principal.WindowsPrincipal(System.Security.Principal.WindowsIdentity.GetCurrent()).IsInRole(System.Security.Principal.WindowsBuiltInRole.Administrator); } catch { return false; } }

        // 1 · SYSTEM
        void System_()
        {
            const string S = "1. System Information";
            try
            {
                using (ManagementObjectSearcher q = new ManagementObjectSearcher("SELECT Caption, Version, BuildNumber, OSArchitecture, LastBootUpTime, InstallDate FROM Win32_OperatingSystem"))
                    foreach (ManagementObject o in q.Get())
                    {
                        Report.Os = Convert.ToString(o["Caption"]) + " " + Convert.ToString(o["Version"]);
                        Add(S, "OS & Version", "Caption", Convert.ToString(o["Caption"]), "", "");
                        Add(S, "OS & Version", "Version", Convert.ToString(o["Version"]), "", "");
                        Add(S, "OS & Version", "Build", Convert.ToString(o["BuildNumber"]), "", "");
                        Add(S, "OS & Version", "Architecture", Convert.ToString(o["OSArchitecture"]), "", "");
                        DateTime boot = ManagementDateTimeConverter.ToDateTime(Convert.ToString(o["LastBootUpTime"]));
                        TimeSpan up = DateTime.Now - boot; Add(S, "Uptime", "Last boot", boot.ToString("yyyy-MM-dd HH:mm:ss"), "", "");
                        Add(S, "Uptime", "Uptime", ((int)up.TotalDays) + "d " + up.Hours + "h " + up.Minutes + "m", up.TotalDays > 30 ? "up for over a month - patches may be pending a reboot" : "", up.TotalDays > 30 ? "warn" : "");
                    }
            }
            catch (Exception ex) { FailItem(S, "OS & Version", "operating system", ex); }
            try
            {
                using (RegistryKey b = RegistryKey.OpenBaseKey(RegistryHive.LocalMachine, RegistryView.Registry64))
                {
                    using (RegistryKey k = b.OpenSubKey(@"SOFTWARE\Microsoft\PowerShell\3\PowerShellEngine")) if (k != null) Add(S, "PowerShell", "Windows PowerShell", Convert.ToString(k.GetValue("PowerShellVersion")), "", "");
                    using (RegistryKey k = b.OpenSubKey(@"SOFTWARE\Microsoft\PowerShell\1\PowerShellEngine")) if (k != null) { string v = Convert.ToString(k.GetValue("PowerShellVersion")); if (v != null && v.StartsWith("2")) Add(S, "PowerShell", "PowerShell v2 engine", v, "the v2 engine is present - a downgrade-attack surface; remove if unused", "warn"); }
                }
            }
            catch (Exception ex) { FailItem(S, "PowerShell", "PowerShell version", ex); }
            try
            {
                List<Hotfix> q = Inventory.Qfe(); q.Sort(delegate (Hotfix a, Hotfix c) { DateTime da = a.InstalledOn ?? DateTime.MinValue, dc = c.InstalledOn ?? DateTime.MinValue; return dc.CompareTo(da); });
                int n = 0; foreach (Hotfix h in q) { if (n++ >= 10) break; Add(S, "Installed Hotfixes (last 10)", "KB" + h.Kb, h.When + (h.Description.Length > 0 ? " · " + h.Description : ""), "", ""); }
                if (q.Count == 0) Add(S, "Installed Hotfixes (last 10)", "hotfixes", "none listed", "", "info");
            }
            catch (Exception ex) { FailItem(S, "Installed Hotfixes (last 10)", "hotfixes", ex); }
        }

        // 2 · USERS & GROUPS
        void Users_()
        {
            const string S = "2. Users & Groups";
            try
            {
                using (ManagementObjectSearcher q = new ManagementObjectSearcher("SELECT Name, Disabled, Lockout, PasswordRequired, PasswordExpires, SID FROM Win32_UserAccount WHERE LocalAccount=True"))
                    foreach (ManagementObject o in q.Get())
                    {
                        bool disabled = ToBool(o["Disabled"]); bool pwReq = ToBool(o["PasswordRequired"]); string name = Convert.ToString(o["Name"]); string sid = Convert.ToString(o["SID"]);
                        string note = ""; string risk = ""; if (!disabled && !pwReq) { note = "enabled with no password required"; risk = "warn"; }
                        if (sid != null && sid.EndsWith("-500") && !disabled) { note = (note.Length > 0 ? note + "; " : "") + "built-in Administrator is enabled"; risk = "warn"; }
                        Add(S, "Local Users", name, (disabled ? "disabled" : "enabled") + " · password " + (pwReq ? "required" : "not required") + " · expires " + (ToBool(o["PasswordExpires"]) ? "yes" : "no"), note, risk);
                    }
            }
            catch (Exception ex) { FailItem(S, "Local Users", "local users", ex); }
            try
            {
                string host = Environment.MachineName.Replace("'", "''");
                using (ManagementObjectSearcher q = new ManagementObjectSearcher(new ManagementScope(@"\\.\root\cimv2"), new ObjectQuery("ASSOCIATORS OF {Win32_Group.Domain='" + host + "',Name='Administrators'} WHERE ResultClass=Win32_Account")))
                {
                    int n = 0; foreach (ManagementObject o in q.Get()) { n++; Add(S, "Local Administrators", Convert.ToString(o["Caption"]) ?? Convert.ToString(o["Name"]), Convert.ToString(o["__CLASS"]), "member of Administrators", n > 3 ? "warn" : ""); }
                    if (n == 0) Add(S, "Local Administrators", "members", "none enumerated", "may need administrator rights", "info");
                    else if (n > 3) Add(S, "Local Administrators", "count", n + " members", "more accounts than typical are local administrators", "warn");
                }
            }
            catch (Exception ex) { FailItem(S, "Local Administrators", "administrators group", ex); }
            try
            {
                HashSet<string> seen = new HashSet<string>();
                using (ManagementObjectSearcher q = new ManagementObjectSearcher("SELECT Antecedent FROM Win32_LoggedOnUser"))
                    foreach (ManagementObject o in q.Get())
                    {
                        string a = Convert.ToString(o["Antecedent"]); string acct = ParseAccount(a); if (acct == null || !seen.Add(acct)) continue; Add(S, "Logged On Users", acct, "", "", "");
                    }
                if (seen.Count == 0) Add(S, "Logged On Users", "sessions", "none enumerated", "", "info");
            }
            catch (Exception ex) { FailItem(S, "Logged On Users", "logged-on users", ex); }
        }
        static string ParseAccount(string reference)
        {
            if (string.IsNullOrEmpty(reference)) return null; string dom = Grab(reference, "Domain=\"", "\""), name = Grab(reference, "Name=\"", "\""); if (name == null) return null; return (dom != null ? dom + "\\" : "") + name;
        }
        static string Grab(string s, string a, string b) { int i = s.IndexOf(a); if (i < 0) return null; i += a.Length; int j = s.IndexOf(b, i); return j < 0 ? null : s.Substring(i, j - i); }

        // 3 · NETWORK
        void Network_()
        {
            const string S = "3. Network";
            try
            {
                foreach (NetworkInterface ni in NetworkInterface.GetAllNetworkInterfaces())
                {
                    if (ni.OperationalStatus != OperationalStatus.Up || ni.NetworkInterfaceType == NetworkInterfaceType.Loopback) continue;
                    foreach (UnicastIPAddressInformation ip in ni.GetIPProperties().UnicastAddresses) if (ip.Address.AddressFamily == System.Net.Sockets.AddressFamily.InterNetwork) Add(S, "IP Configuration", ni.Name, ip.Address.ToString() + "/" + ip.PrefixLength, ni.Description, "");
                }
            }
