// System Recon & Audit engine (no UI). A faithful C# port of the "PowerShell System Recon & Audit"
// master script: system, users and groups, network, security posture, persistence surface, running
// processes and recent security events. Read-only. It never runs the .ps1 - it collects the same
// facts through WMI/CIM, the registry, COM (firewall, Task Scheduler) and the event log, so there is
// no console flash and each fact becomes a row with a risk flag. The report exports to Markdown,
// JSON and PDF (a minimal built-in PDF writer - no external library).
using System;
using System.Collections.Generic;
using System.Diagnostics;
using System.Diagnostics.Eventing.Reader;
using System.Globalization;
using System.IO;
using System.Management;
using System.Net.NetworkInformation;
using System.Text;
using System.Threading;
